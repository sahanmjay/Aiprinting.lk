// Bundles src/lib/pricing.ts (+ seed prices it imports) into api/_pricing.js: one self-contained ES module
// with no imports, so the Vercel function needs no TypeScript or src/ resolution at runtime.
// Runs as part of `npm run build`; commit the output. scripts/test_pricing.mjs checks it is up to date.
import { build } from 'rolldown';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

export async function bundlePricing(write = true) {
  const out = await build({
    cwd: root,
    input: 'src/lib/pricing.ts',
    platform: 'node',
    write,
    output: { file: 'api/_pricing.js', format: 'esm', banner: '// GENERATED by scripts/bundle-pricing.mjs from src/lib/pricing.ts — do not edit.' },
  });
  return out.output[0].code;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await bundlePricing();
  console.log('api/_pricing.js bundled');
}
