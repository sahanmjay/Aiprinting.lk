// Helper to generate a 126-cell price matrix
export function generateCardPriceMatrix(productId: string, isDouble: boolean): PriceMatrixCell[] {
  const cells: PriceMatrixCell[] = [];
  for (const paper of VISITING_CARD_PAPERS) {
    for (const qty of VISITING_CARD_QUANTITIES) {
      const base = isDouble ? qty.baseDouble : qty.baseSingle;
      // Round to nearest 50 LKR
      const calculatedPrice = Math.round((base * paper.multiplier) / 50) * 50;
      cells.push({
        id: `pm-${productId}-${paper.id}-${qty.id}`,
        productId,
        optionValueA: paper.id,
        optionValueB: qty.id,
        price: calculatedPrice,
        isActive: true,
      });
    }
  }
  return cells;
}

