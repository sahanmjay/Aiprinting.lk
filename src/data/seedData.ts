// Every product's options and prices live in ./priceTables.ts (imported from the old aiprinting.lk shop).
const CATEGORY_NAME = Object.fromEntries(SEED_CATEGORIES.map((c) => [c.id, c.name]));
const CREATED_AT = new Date().toISOString();

function makeProduct(p: {
  id: string;
  slug: string;
  name: string;
  categoryId: string;
  shortDescription: string;
  longDescription: string;
  deliveryNote: string;
  sizeNote: string;
  image: string;
  imageAlt: string;
  sortOrder: number;
  isFeatured?: boolean;
  isHot?: boolean;
  specs?: Record<string, string>;
}): Product {
  const table = PRICE_TABLES[p.id];
  const prices = (table.prices ?? []).flat().filter((x): x is number => x != null);
  return {
    id: p.id,
    slug: p.slug,
    name: p.name,
    shortDescription: p.shortDescription,
    longDescription: p.longDescription,
    categoryId: p.categoryId,
    categoryName: CATEGORY_NAME[p.categoryId],
    basePrice: prices.length ? Math.min(...prices) : 0, // 0 = price on request
    isVariable: true,
    isFeatured: !!p.isFeatured,
    isHot: !!p.isHot,
    deliveryNote: p.deliveryNote,
    sizeNote: p.sizeNote,
    isActive: true,
    sortOrder: p.sortOrder,
    createdAt: CREATED_AT,
    images: [{ id: `img-${p.id}`, productId: p.id, imageUrl: p.image, altText: p.imageAlt, sortOrder: 1, isPrimary: true }],
    optionGroups: tableOptionGroups(p.id, table),
    specs: p.specs,
  };
}

